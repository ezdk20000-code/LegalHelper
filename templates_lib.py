def ensure_builtin(root):
    """Создать недостающие встроенные шаблоны в root/Встроенные/<категория>/. Возвращает число созданных."""
    made = 0
    for spec in T:
        folder = os.path.join(root, "Встроенные", spec["cat"])
        os.makedirs(folder, exist_ok=True)
        p = os.path.join(folder, spec["name"] + ".docx")
        if not os.path.exists(p):
            _build(spec, p)
            made += 1
    os.makedirs(os.path.join(root, "Мои шаблоны"), exist_ok=True)
    return made


