def _build_speech(spec, path):
    """План выступления: крупно, с нумерованными разделами и пунктами — удобно читать с листа."""
    import docx
    from docx.shared import Pt, Cm, RGBColor
    from docx.enum.text import WD_ALIGN_PARAGRAPH
    from docx.oxml.ns import qn
    from docx.oxml import OxmlElement
    d = docx.Document()
    for sct in d.sections:
        sct.left_margin, sct.right_margin = Cm(2.2), Cm(2)
        sct.top_margin, sct.bottom_margin = Cm(1.8), Cm(1.8)
    st = d.styles["Normal"]
    st.font.name = "Times New Roman"
    st.font.size = Pt(14)
    st.paragraph_format.space_after = Pt(0)
    try:
        st.element.rPr.rFonts.set(qn("w:eastAsia"), "Times New Roman")
    except Exception:
        pass
    accent = RGBColor(0x1F, 0x38, 0x64)

    def par(text="", bold=False, size=None, color=None, align=WD_ALIGN_PARAGRAPH.LEFT, before=0, after=0,
            left=None, spacing=1.25):
        p = d.add_paragraph()
        p.alignment = align
        pf = p.paragraph_format
        pf.space_before, pf.space_after, pf.line_spacing = Pt(before), Pt(after), spacing
        if left is not None:
            pf.left_indent = left
        r = p.add_run(text)
        r.bold = bold
        if size:
            r.font.size = Pt(size)
        if color:
            r.font.color.rgb = color
        return p

    def rule(p):
        pPr = p._p.get_or_add_pPr()
        bdr = OxmlElement("w:pBdr")
        b = OxmlElement("w:bottom")
        for k, v in (("w:val", "single"), ("w:sz", "6"), ("w:space", "4"), ("w:color", "1F3864")):
            b.set(qn(k), v)
        bdr.append(b)
        pPr.append(bdr)

    par("ВЫСТУПЛЕНИЕ В СУДЕБНОМ ЗАСЕДАНИИ", bold=True, size=17, color=accent, align=WD_ALIGN_PARAGRAPH.CENTER)
    rule(par("план речи", size=12, align=WD_ALIGN_PARAGRAPH.CENTER, after=6))
    t = d.add_table(rows=0, cols=2)
    t.autofit = False
    for label, val in spec["info"]:
        cells = t.add_row().cells
        cells[0].width, cells[1].width = Cm(3.6), Cm(13.2)
        r = cells[0].paragraphs[0].add_run(label)
        r.font.size = Pt(11)
        r.font.color.rgb = RGBColor(0x59, 0x59, 0x59)
        r2 = cells[1].paragraphs[0].add_run(val)
        r2.font.size = Pt(12)
        r2.bold = True
    for col, wdt in zip(t.columns, (Cm(3.6), Cm(13.2))):
        col.width = wdt
    for i, (title, lines) in enumerate(spec["sections"], 1):
        rule(par(f"{i}. {title}", bold=True, size=15, color=accent, before=14, after=4))
        for line in lines:
            par(line, left=Cm(0.6), spacing=1.35, after=3)
    par(spec["ending"], bold=True, before=16, left=Cm(0.6))
    d.save(path)


