def help_dir():
    base = getattr(sys, "_MEIPASS", os.path.dirname(os.path.abspath(__file__)))
    return os.path.join(base, "help")


def _png_size(path):
    """Ширина и высота PNG без сторонних библиотек."""
    import struct
    try:
        with open(path, "rb") as f:
            head = f.read(24)
        return struct.unpack(">II", head[16:24])
    except Exception:
        return None


def img(name, caption="", width=820):
    cap = f'<p class="cap">{caption}</p>' if caption else ""
    size = _png_size(os.path.join(help_dir(), "img", name + ".png"))
    if size:
        w0, h0 = size
        width = min(width, w0)
        height = round(h0 * width / w0)
        dims = f'width="{width}" height="{height}"'
    else:
        dims = f'width="{width}"'
    return f'<p class="pic"><img src="img/{name}.png" {dims}></p>{cap}'


def steps(*items):
    return "<ol>" + "".join(f"<li>{i}</li>" for i in items) + "</ol>"


def bullets(*items):
    return "<ul>" + "".join(f"<li>{i}</li>" for i in items) + "</ul>"


def tip(text):
    return f'<table class="tip" width="100%" cellpadding="10"><tr><td>{text}</td></tr></table>'


def keys(k):
    return f'<span class="key">{k}</span>'


