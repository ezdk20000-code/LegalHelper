def _d(s):
    return _dt.date.fromisoformat(s)


_cache = {}


def year_calendar(year):
    """(множество нерабочих дат, множество рабочих выходных, утверждён ли календарь)."""
    if year in _cache:
        return _cache[year]
    if year in HOLIDAYS:
        off = {_d(f"{year}-{md}") for md in HOLIDAYS[year]}
        work = {_d(f"{year}-{md}") for md in WORKING_WEEKENDS.get(year, [])}
        res = (off, work, True)
    else:     # приблизительно: праздники + перенос с выходного на следующий будний (кроме января)
        off = set()
        for md in FIXED_HOLIDAYS:
            d = _d(f"{year}-{md}")
            off.add(d)
            if d.weekday() >= 5 and d.month != 1:
                n = d + _dt.timedelta(days=1)
                while n.weekday() >= 5 or n in off:
                    n += _dt.timedelta(days=1)
                off.add(n)
        res = (off, set(), False)
    _cache[year] = res
    return res


def is_workday(d):
    off, work, _ = year_calendar(d.year)
    if d in work:
        return True
    return d.weekday() < 5 and d not in off


